def evaluate_native_old_checkpoint_on_manifest(df: pd.DataFrame, image_path_col: str, out_dir: Path, split_name: str) -> Tuple[pd.DataFrame, Dict[str, Any]]:
    model = YOLO(str(CFG.old_model_path))
    transform = build_eval_transform(CFG.image_size)
    ds = ManifestImageDataset(df, image_path_col=image_path_col, transform=transform)
    loader = torch.utils.data.DataLoader(
        ds,
        batch_size=CFG.eval_batch_size,
        shuffle=False,
        num_workers=CFG.num_workers,
        pin_memory=CFG.device.startswith("cuda"),
    )
    net = model.model.to(CFG.device)
    net.eval()
    rows = []
    with torch.inference_mode():
        for batch_x, batch_y, batch_meta in tqdm(loader, desc=f"baseline {split_name}", leave=False):
            batch_x = batch_x.to(CFG.device)
            logits = extract_logits(net(batch_x))
            probs = compute_probabilities_from_logits(logits)
            conf, preds = probs.max(dim=1)
            for i in range(len(batch_y)):
                rec = {
                    "filepath": batch_meta["filepath"][i] if isinstance(batch_meta["filepath"], list) else batch_meta["filepath"],
                    "source_filepath": batch_meta["source_filepath"][i] if isinstance(batch_meta["source_filepath"], list) else batch_meta["source_filepath"],
                    "file_sha1": batch_meta["file_sha1"][i] if isinstance(batch_meta["file_sha1"], list) else batch_meta["file_sha1"],
                    "label_true_idx": int(batch_y[i].item()),
                    "label_true": CFG.class_names[int(batch_y[i].item())],
                    "pred_idx": int(preds[i].item()),
                    "pred_label": CFG.class_names[int(preds[i].item())],
                    "confidence": float(conf[i].item()),
                    "tta_variance": 0.0,
                }
                for class_idx, class_name in enumerate(CFG.class_names):
                    rec[f"logit_{class_name}"] = float(logits[i, class_idx].detach().cpu().item())
                    rec[f"prob_{class_name}"] = float(probs[i, class_idx].detach().cpu().item())
                rec["is_correct"] = rec["label_true_idx"] == rec["pred_idx"]
                rows.append(rec)
    pred_df = pd.DataFrame(rows)
    summary = summarize_prediction_artifacts(pred_df, out_dir=out_dir, split_name=split_name)
    return pred_df, summary

