def enrich_leaderboard(df: pd.DataFrame) -> pd.DataFrame:
    if df.empty:
        return df
    work = df.copy()
    for col in [
        "valid_macro_f1", "valid_balanced_accuracy", "valid_worst_class_recall", "valid_ece",
        "valid_challenge_mean_macro_f1", "valid_challenge_worst_macro_f1", "test_macro_f1",
        "test_balanced_accuracy", "test_worst_class_recall", "test_ece", "valid_brier_score",
    ]:
        if col not in work.columns:
            work[col] = np.nan

    work["recipe_key"] = work.apply(
        lambda r: "__".join([
            normalize_token(r.get("family", "")),
            normalize_token(r.get("architecture", "")),
            normalize_token(r.get("branch_name", "")),
            normalize_token(r.get("aug_policy", "")),
            normalize_token(f"img{r.get('image_size', '')}"),
            normalize_token(f"lr{r.get('lr', '')}"),
            normalize_token(f"wd{r.get('weight_decay', '')}"),
            normalize_token(f"drop{r.get('dropout', '')}"),
            normalize_token(f"ls{r.get('label_smoothing', '')}"),
            normalize_token(f"freeze{r.get('freeze_backbone_epochs', '')}"),
            normalize_token(r.get("class_balancing", "")),
            normalize_token(r.get("loss_name", "")),
        ]),
        axis=1,
    )
    work["clean_rank_score"] = (
        0.45 * work["valid_macro_f1"].fillna(-1.0)
        + 0.25 * work["valid_balanced_accuracy"].fillna(-1.0)
        + 0.20 * work["valid_worst_class_recall"].fillna(-1.0)
        - 0.05 * work["valid_ece"].fillna(1.0)
    )
    robust_component = work["valid_challenge_mean_macro_f1"].fillna(work["valid_macro_f1"])
    robust_worst = work["valid_challenge_worst_macro_f1"].fillna(work["valid_macro_f1"])
    work["robust_rank_score"] = (
        0.35 * work["valid_macro_f1"].fillna(-1.0)
        + 0.20 * work["valid_balanced_accuracy"].fillna(-1.0)
        + 0.15 * work["valid_worst_class_recall"].fillna(-1.0)
        + 0.20 * robust_component.fillna(-1.0)
        + 0.10 * robust_worst.fillna(-1.0)
        - 0.05 * work["valid_ece"].fillna(1.0)
    )
    work["calibration_rank_score"] = (
        work["valid_macro_f1"].fillna(-1.0)
        - 0.25 * work["valid_ece"].fillna(1.0)
        - 0.10 * work["valid_brier_score"].fillna(1.0)
    )
    return work

