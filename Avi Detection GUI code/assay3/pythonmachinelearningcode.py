def directory_summary(root: Path, max_depth: int = 3, max_entries_per_dir: int = 40) -> None:
    root = Path(root)
    if not root.exists():
        print(f"[directory_summary] Missing path: {root}")
        return
    print(f"Directory summary for: {root.resolve()}")
    for path in sorted(root.rglob("*")):
        rel = path.relative_to(root)
        depth = len(rel.parts)
        if depth > max_depth:
            continue
        if path.is_dir():
            try:
                children = list(path.iterdir())
            except Exception:
                children = []
            n_dirs = sum(p.is_dir() for p in children)
            n_files = sum(p.is_file() for p in children)
            print(f"[DIR ] {rel} (dirs={n_dirs}, files={n_files})")
        else:
            print(f"[FILE] {rel}")

def find_dataset_root(download_path: Path) -> Path:
    download_path = Path(download_path)
    if (download_path / "data.yaml").exists():
        return download_path
    candidates = sorted(download_path.rglob("data.yaml"))
    if candidates:
        return candidates[0].parent
    return download_path

def read_text_if_exists(path: Path) -> str:
    try:
        return path.read_text(encoding="utf-8", errors="ignore")
    except Exception:
        return ""

def parse_upstream_preprocessing_notes(dataset_root: Path) -> Dict[str, Any]:
    notes = {}
    for readme_name in ["README.roboflow.txt", "README.dataset.txt"]:
        txt = read_text_if_exists(dataset_root / readme_name)
        if txt:
            notes[readme_name] = txt[:4000]
    data_yaml = {}
    data_yaml_path = dataset_root / "data.yaml"
    if data_yaml_path.exists():
        try:
            data_yaml = yaml.safe_load(data_yaml_path.read_text(encoding="utf-8"))
        except Exception as exc:
            data_yaml = {"_parse_error": str(exc)}
    return {"readmes": notes, "data_yaml": data_yaml}

