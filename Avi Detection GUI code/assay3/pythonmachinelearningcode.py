def clamp_xyxy(x1: float, y1: float, x2: float, y2: float, w: int, h: int) -> Tuple[int, int, int, int]:
    x1 = int(max(0, min(round(x1), w - 1)))
    y1 = int(max(0, min(round(y1), h - 1)))
    x2 = int(max(x1 + 1, min(round(x2), w)))
    y2 = int(max(y1 + 1, min(round(y2), h)))
    return x1, y1, x2, y2

def bbox_xyxy_from_record(row: pd.Series) -> Optional[Tuple[int, int, int, int]]:
    if any(pd.isna(row.get(col)) for col in ["bbox_xc", "bbox_yc", "bbox_w", "bbox_h", "width", "height"]):
        return None
    x1, y1, x2, y2 = yolo_bbox_to_xyxy(
        float(row["bbox_xc"]),
        float(row["bbox_yc"]),
        float(row["bbox_w"]),
        float(row["bbox_h"]),
        int(row["width"]),
        int(row["height"]),
    )
    return clamp_xyxy(x1, y1, x2, y2, int(row["width"]), int(row["height"]))

def expand_bbox(box: Tuple[int, int, int, int], image_size: Tuple[int, int], margin_frac: float) -> Tuple[int, int, int, int]:
    x1, y1, x2, y2 = box
    w = x2 - x1
    h = y2 - y1
    margin_x = w * margin_frac
    margin_y = h * margin_frac
    return clamp_xyxy(x1 - margin_x, y1 - margin_y, x2 + margin_x, y2 + margin_y, image_size[0], image_size[1])

def robust_background_color(img: Image.Image) -> Tuple[int, int, int]:
    arr = np.asarray(img.convert("RGB"))
    return tuple(int(np.median(arr[:, :, i])) for i in range(3))

def resize_with_pad(img: Image.Image, target_size: int, fill: Tuple[int, int, int]) -> Image.Image:
    img = img.convert("RGB")
    w, h = img.size
    max_side = max(w, h)
    pad_left = (max_side - w) // 2
    pad_right = max_side - w - pad_left
    pad_top = (max_side - h) // 2
    pad_bottom = max_side - h - pad_top
    img = ImageOps.expand(img, border=(pad_left, pad_top, pad_right, pad_bottom), fill=fill)
    img = img.resize((target_size, target_size), Image.Resampling.BILINEAR)
    return img

def build_branch_image(img: Image.Image, row: pd.Series, branch_name: str) -> Tuple[Image.Image, str]:
    img = img.convert("RGB")
    fill = robust_background_color(img)
    box = bbox_xyxy_from_record(row)

    if branch_name == "RAW":
        return img.copy(), "raw_copy"

    if box is None:
        return resize_with_pad(img, CFG.branch_export_size, fill), f"{branch_name.lower()}_fallback_no_bbox"

    if branch_name == "TIGHT_CROP":
        crop_box = expand_bbox(box, img.size, CFG.tight_crop_margin)
        crop = img.crop(crop_box)
        return resize_with_pad(crop, CFG.branch_export_size, fill), "tight_crop_bbox"

    if branch_name == "BACKGROUND_REDUCED":
        crop_box = expand_bbox(box, img.size, CFG.background_margin)
        x1, y1, x2, y2 = crop_box
        arr = np.asarray(img.convert("RGB")).copy()
        blurred = np.asarray(img.filter(ImageFilter.GaussianBlur(radius=6)).convert("RGB"))
        mask = np.zeros(arr.shape[:2], dtype=np.uint8)
        mask[y1:y2, x1:x2] = 1
        arr[mask == 0] = blurred[mask == 0]
        out = Image.fromarray(arr)
        return out.resize((CFG.branch_export_size, CFG.branch_export_size), Image.Resampling.BILINEAR), "background_reduced_bbox"

    if branch_name == "STANDARDIZED_FRAME":
        crop_box = expand_bbox(box, img.size, CFG.standardized_frame_margin)
        crop = img.crop(crop_box).convert("RGB")
        crop = resize_with_pad(crop, int(CFG.branch_export_size * CFG.standardized_object_fraction), fill)
        canvas = Image.new("RGB", (CFG.branch_export_size, CFG.branch_export_size), color=fill)
        offset_x = (CFG.branch_export_size - crop.size[0]) // 2
        offset_y = (CFG.branch_export_size - crop.size[1]) // 2
        canvas.paste(crop, (offset_x, offset_y))
        return canvas, "standardized_frame_bbox"

    raise KeyError(f"Unknown branch_name: {branch_name}")

