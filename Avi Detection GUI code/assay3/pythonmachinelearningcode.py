SPLIT_ALIASES = {
    "train": "train",
    "training": "train",
    "trn": "train",
    "valid": "valid",
    "val": "valid",
    "validation": "valid",
    "dev": "valid",
    "test": "test",
    "testing": "test",
}

def normalize_token(value: Any) -> str:
    value = "" if value is None else str(value)
    value = value.strip().lower()
    value = re.sub(r"[^a-z0-9]+", "_", value)
    value = re.sub(r"_+", "_", value).strip("_")
    return value

def strip_roboflow_suffix(filename_or_stem: str) -> str:
    s = filename_or_stem
    s = re.sub(r"\.rf\.[a-f0-9]+$", "", s)
    s = re.sub(r"\.rf\.[a-z0-9]+$", "", s)
    return s

def infer_source_split_from_path(path: Path) -> str:
    for part in path.parts:
        key = normalize_token(part)
        if key in SPLIT_ALIASES:
            return SPLIT_ALIASES[key]
    return "unknown"

def safe_image_open(path: Path) -> Tuple[Optional[Image.Image], Optional[str]]:
    try:
        img = Image.open(path)
        img.load()
        return img, None
    except Exception as exc:
        return None, f"{type(exc).__name__}: {exc}"

def compute_sha1(path: Path, chunk_size: int = 1024 * 1024) -> str:
    h = __import__("hashlib").sha1()
    with open(path, "rb") as f:
        while True:
            chunk = f.read(chunk_size)
            if not chunk:
                break
            h.update(chunk)
    return h.hexdigest()

def compute_dhash(path: Path, hash_size: int = 8) -> Optional[int]:
    img, err = safe_image_open(path)
    if img is None:
        return None
    try:
        img = img.convert("L").resize((hash_size + 1, hash_size), Image.Resampling.BILINEAR)
        arr = np.asarray(img, dtype=np.int16)
        diff = arr[:, 1:] > arr[:, :-1]
        bit_string = "".join("1" if v else "0" for v in diff.flatten())
        return int(bit_string, 2)
    except Exception:
        return None

def hamming_distance_int(a: Optional[int], b: Optional[int]) -> Optional[int]:
    if a is None or b is None:
        return None
    return int((a ^ b).bit_count())

def find_label_file_for_image(image_path: Path) -> Optional[Path]:
    parts = list(image_path.parts)
    if "images" in parts:
        idx = parts.index("images")
        parts[idx] = "labels"
        label_path = Path(*parts).with_suffix(".txt")
        if label_path.exists():
            return label_path
    candidate = image_path.with_suffix(".txt")
    if candidate.exists():
        return candidate
    return None

def yolo_bbox_to_xyxy(xc: float, yc: float, w: float, h: float, img_w: int, img_h: int) -> Tuple[float, float, float, float]:
    bw = w * img_w
    bh = h * img_h
    x1 = (xc * img_w) - bw / 2.0
    y1 = (yc * img_h) - bh / 2.0
    x2 = (xc * img_w) + bw / 2.0
    y2 = (yc * img_h) + bh / 2.0
    return x1, y1, x2, y2

def xyxy_to_yolo_bbox(x1: float, y1: float, x2: float, y2: float, img_w: int, img_h: int) -> Tuple[float, float, float, float]:
    x1 = max(0.0, min(x1, img_w))
    y1 = max(0.0, min(y1, img_h))
    x2 = max(0.0, min(x2, img_w))
    y2 = max(0.0, min(y2, img_h))
    xc = ((x1 + x2) / 2.0) / img_w
    yc = ((y1 + y2) / 2.0) / img_h
    w = max(1.0, x2 - x1) / img_w
    h = max(1.0, y2 - y1) / img_h
    return xc, yc, w, h

def parse_yolo_label_file(label_path: Optional[Path], img_w: int, img_h: int) -> Dict[str, Any]:
    if label_path is None or not Path(label_path).exists():
        return {
            "label_path": None,
            "label_source_format": "none",
            "class_id": None,
            "bbox_count": 0,
            "bbox_xc": None,
            "bbox_yc": None,
            "bbox_w": None,
            "bbox_h": None,
            "label_note": "missing_label_file",
        }

    lines = [ln.strip() for ln in Path(label_path).read_text(encoding="utf-8", errors="ignore").splitlines() if ln.strip()]
    if not lines:
        return {
            "label_path": str(label_path),
            "label_source_format": "yolo",
            "class_id": None,
            "bbox_count": 0,
            "bbox_xc": None,
            "bbox_yc": None,
            "bbox_w": None,
            "bbox_h": None,
            "label_note": "empty_label_file",
        }

    class_ids = []
    boxes_xyxy = []
    for line in lines:
        parts = line.split()
        if len(parts) < 5:
            continue
        class_id = int(float(parts[0]))
        coords = [float(v) for v in parts[1:5]]
        class_ids.append(class_id)
        boxes_xyxy.append(yolo_bbox_to_xyxy(coords[0], coords[1], coords[2], coords[3], img_w, img_h))

    if not class_ids:
        return {
            "label_path": str(label_path),
            "label_source_format": "yolo",
            "class_id": None,
            "bbox_count": 0,
            "bbox_xc": None,
            "bbox_yc": None,
            "bbox_w": None,
            "bbox_h": None,
            "label_note": "unparseable_label_file",
        }

    unique_classes = sorted(set(class_ids))
    if len(unique_classes) > 1:
        label_note = "multiple_classes_in_single_image"
        class_id = unique_classes[0]
    else:
        label_note = "ok"
        class_id = unique_classes[0]

    x1 = min(b[0] for b in boxes_xyxy)
    y1 = min(b[1] for b in boxes_xyxy)
    x2 = max(b[2] for b in boxes_xyxy)
    y2 = max(b[3] for b in boxes_xyxy)
    xc, yc, w, h = xyxy_to_yolo_bbox(x1, y1, x2, y2, img_w, img_h)

    return {
        "label_path": str(label_path),
        "label_source_format": "yolo",
        "class_id": int(class_id),
        "bbox_count": int(len(boxes_xyxy)),
        "bbox_xc": float(xc),
        "bbox_yc": float(yc),
        "bbox_w": float(w),
        "bbox_h": float(h),
        "label_note": label_note,
    }

def infer_label_from_class_folder(path: Path, class_names: Sequence[str]) -> Optional[str]:
    normalized = {normalize_token(name): name for name in class_names}
    for part in reversed(path.parts[:-1]):
        key = normalize_token(part)
        if key in normalized:
            return normalized[key]
    return None

def parse_metadata_from_name(path: Path) -> Dict[str, Any]:
    filename = path.name
    stem = strip_roboflow_suffix(path.stem)
    stem_no_ext = strip_roboflow_suffix(path.name.split(".")[0])

    meta: Dict[str, Any] = {
        "base_stem": stem,
        "session_date": None,
        "session_time": None,
        "session_hour": None,
        "session_minute_bucket": None,
        "source_kind": None,
        "setup_hint": None,
        "run_hint": None,
        "batch_hint": None,
        "strain_hint": None,
        "metadata_parse_note": "",
    }

    capture_match = re.search(r"capture_(\d{8})_(\d{6})", stem_no_ext, flags=re.IGNORECASE)
    screenshot_match = re.search(
        r"screenshot[-_](\d{4})[-_](\d{2})[-_](\d{2}).*?at[-_](\d{1,2})[-_](\d{2})",
        stem_no_ext,
        flags=re.IGNORECASE,
    )

    if capture_match:
        date_str, time_str = capture_match.groups()
        meta["session_date"] = date_str
        meta["session_time"] = time_str
        meta["session_hour"] = time_str[:2]
        minute = int(time_str[2:4])
        meta["session_minute_bucket"] = f"{minute // max(1, CFG.group_time_bucket_minutes):02d}"
        meta["source_kind"] = "capture"
        meta["metadata_parse_note"] = "capture_pattern"
    elif screenshot_match:
        yyyy, mm, dd, hh, minute = screenshot_match.groups()
        date_str = f"{yyyy}{mm}{dd}"
        hh_int = int(hh)
        meta["session_date"] = date_str
        meta["session_time"] = f"{hh_int:02d}{int(minute):02d}00"
        meta["session_hour"] = f"{hh_int:02d}"
        meta["session_minute_bucket"] = f"{int(minute) // max(1, CFG.group_time_bucket_minutes):02d}"
        meta["source_kind"] = "screenshot"
        meta["metadata_parse_note"] = "screenshot_pattern"
    else:
        meta["metadata_parse_note"] = "filename_pattern_not_found"

    # Parent-folder hints for setup / run / batch / strain.
    parent_tokens = [normalize_token(p) for p in path.parts[:-1]]
    informative_tokens = [p for p in parent_tokens if p not in SPLIT_ALIASES and p not in {"images", "labels"}]
    if informative_tokens:
        meta["setup_hint"] = informative_tokens[-1]
        if len(informative_tokens) >= 2:
            meta["run_hint"] = informative_tokens[-2]
        if len(informative_tokens) >= 3:
            meta["batch_hint"] = informative_tokens[-3]

    strain_match = re.search(r"(line|strain|stock)[-_]?([a-z0-9]+)", stem_no_ext, flags=re.IGNORECASE)
    if strain_match:
        meta["strain_hint"] = normalize_token("_".join(strain_match.groups()))

    return meta

def infer_group_id(record: Dict[str, Any], time_bucket_minutes: int) -> str:
    components = []
    if record.get("session_date"):
        components.append(str(record["session_date"]))
    if record.get("session_hour"):
        components.append(f"h{record['session_hour']}")
    if record.get("session_minute_bucket") is not None:
        components.append(f"b{record['session_minute_bucket']}")
    if record.get("setup_hint"):
        components.append(str(record["setup_hint"]))
    if record.get("run_hint"):
        components.append(str(record["run_hint"]))
    if record.get("source_kind"):
        components.append(str(record["source_kind"]))
    if not components:
        components.append(record.get("base_stem", "ungrouped"))
    return "__".join([normalize_token(c) for c in components if c])

def build_manifest_record(image_path: Path, class_names: Sequence[str], label_override: Dict[int, str]) -> Dict[str, Any]:
    img, img_err = safe_image_open(image_path)
    record: Dict[str, Any] = {
        "filepath": str(image_path.resolve()),
        "filename": image_path.name,
        "file_size_bytes": image_path.stat().st_size if image_path.exists() else None,
        "source_split": infer_source_split_from_path(image_path),
        "parent_1": image_path.parent.name if image_path.parent else None,
        "parent_2": image_path.parent.parent.name if image_path.parent and image_path.parent.parent else None,
        "parent_3": image_path.parent.parent.parent.name if image_path.parent and image_path.parent.parent and image_path.parent.parent.parent else None,
        "corrupt": img is None,
        "corrupt_reason": img_err,
    }

    if img is not None:
        record["width"], record["height"] = img.size
    else:
        record["width"], record["height"] = None, None

    record["file_sha1"] = compute_sha1(image_path) if image_path.exists() else None
    record["dhash64"] = compute_dhash(image_path) if CFG.compute_dhash and image_path.exists() else None

    label_file = find_label_file_for_image(image_path) if image_path.exists() else None
    if img is not None:
        label_info = parse_yolo_label_file(label_file, img_w=img.size[0], img_h=img.size[1])
    else:
        label_info = {
            "label_path": str(label_file) if label_file else None,
            "label_source_format": "none",
            "class_id": None,
            "bbox_count": 0,
            "bbox_xc": None,
            "bbox_yc": None,
            "bbox_w": None,
            "bbox_h": None,
            "label_note": "image_corrupt",
        }
    record.update(label_info)

    label_name = None
    if record.get("class_id") is not None:
        label_name = label_override.get(int(record["class_id"]))
    if label_name is None:
        label_name = infer_label_from_class_folder(image_path, class_names)

    record["label"] = label_name
    record["label_idx"] = class_names.index(label_name) if label_name in class_names else None

    meta = parse_metadata_from_name(image_path)
    record.update(meta)
    record["group_id"] = infer_group_id(record, time_bucket_minutes=CFG.group_time_bucket_minutes)
    record["parse_notes"] = ";".join([n for n in [record.get("label_note"), record.get("metadata_parse_note")] if n])
    return record

def build_canonical_manifest(dataset_root: Path, class_names: Sequence[str], label_override: Dict[int, str]) -> pd.DataFrame:
    rows: List[Dict[str, Any]] = []
    image_paths = sorted([p for p in dataset_root.rglob("*") if p.is_file() and p.suffix.lower() in IMAGE_EXTENSIONS])
    print(f"Discovered {len(image_paths)} candidate image files.")
    for image_path in tqdm(image_paths, desc="Building manifest"):
        rows.append(build_manifest_record(image_path, class_names=class_names, label_override=label_override))
    df = pd.DataFrame(rows)

    expected_cols = [
        "filepath", "filename", "label", "label_idx", "source_split",
        "file_sha1", "file_size_bytes", "width", "height",
        "parent_1", "parent_2", "parent_3",
        "session_date", "session_time", "session_hour",
        "setup_hint", "run_hint", "batch_hint", "strain_hint",
        "group_id", "corrupt", "parse_notes",
        "label_path", "label_source_format", "class_id", "bbox_count",
        "bbox_xc", "bbox_yc", "bbox_w", "bbox_h", "dhash64",
    ]
    for col in expected_cols:
        if col not in df.columns:
            df[col] = None
    return df

def summarize_class_balance(df: pd.DataFrame, class_names: Sequence[str]) -> pd.DataFrame:
    summary = (
        df[~df["corrupt"]]
        .groupby(["source_split", "label"])
        .size()
        .unstack(fill_value=0)
        .reindex(columns=class_names, fill_value=0)
    )
    return summary

def exact_duplicate_table(df: pd.DataFrame) -> pd.DataFrame:
    dup = df.groupby("file_sha1").agg(
        n=("filepath", "size"),
        splits=("source_split", lambda x: sorted(set(x))),
        labels=("label", lambda x: sorted(set(x))),
        filepaths=("filepath", list),
    ).reset_index()
    dup = dup[dup["n"] > 1].sort_values(["n", "file_sha1"], ascending=[False, True]).reset_index(drop=True)
    return dup

def suspicious_filename_reuse_table(df: pd.DataFrame) -> pd.DataFrame:
    stem_series = df["filename"].astype(str).map(lambda x: strip_roboflow_suffix(Path(x).stem))
    tmp = df.copy()
    tmp["filename_base"] = stem_series
    reuse = tmp.groupby("filename_base").agg(
        n=("filepath", "size"),
        splits=("source_split", lambda x: sorted(set(x))),
        labels=("label", lambda x: sorted(set(x))),
        filepaths=("filepath", list),
    ).reset_index()
    reuse = reuse[reuse["n"] > 1].sort_values(["n", "filename_base"], ascending=[False, True]).reset_index(drop=True)
    return reuse

def near_duplicate_pairs_table(df: pd.DataFrame, threshold: int = 5, max_pairs: int = 5000) -> pd.DataFrame:
    work = df[~df["corrupt"] & df["dhash64"].notna()].reset_index(drop=True).copy()
    rows = []
    for i in range(len(work)):
        a = work.iloc[i]
        for j in range(i + 1, len(work)):
            b = work.iloc[j]
            dist = hamming_distance_int(int(a["dhash64"]), int(b["dhash64"]))
            if dist is not None and dist <= threshold:
                rows.append({
                    "idx_a": int(i),
                    "idx_b": int(j),
                    "filepath_a": a["filepath"],
                    "filepath_b": b["filepath"],
                    "label_a": a["label"],
                    "label_b": b["label"],
                    "source_split_a": a["source_split"],
                    "source_split_b": b["source_split"],
                    "hamming_distance": int(dist),
                    "same_label": a["label"] == b["label"],
                    "cross_split": a["source_split"] != b["source_split"],
                })
                if len(rows) >= max_pairs:
                    return pd.DataFrame(rows)
    return pd.DataFrame(rows)

def cross_split_group_overlap_table(df: pd.DataFrame) -> pd.DataFrame:
    tmp = (
        df.groupby(["group_id", "source_split"]).size().unstack(fill_value=0)
        if "group_id" in df.columns else pd.DataFrame()
    )
    if tmp.empty:
        return pd.DataFrame()
    tmp["num_splits_present"] = (tmp > 0).sum(axis=1)
    overlap = tmp[tmp["num_splits_present"] > 1].reset_index()
    return overlap.sort_values("num_splits_present", ascending=False).reset_index(drop=True)

