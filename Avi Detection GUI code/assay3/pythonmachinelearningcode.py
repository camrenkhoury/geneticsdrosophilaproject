# PATCH — torchvision pretrained download fallback

def build_torchvision_model(architecture: str, num_classes: int, pretrained: bool, dropout: float) -> nn.Module:
    arch = architecture.lower()
    def _safe_construct(builder, weights_obj):
        if pretrained:
            try:
                return builder(weights=weights_obj)
            except Exception as exc:
                print(f"WARNING: pretrained weights unavailable for {architecture}, falling back to random init. Reason: {exc}")
                return builder(weights=None)
        return builder(weights=None)

    if arch == "resnet18":
        model = _safe_construct(torchvision.models.resnet18, torchvision.models.ResNet18_Weights.IMAGENET1K_V1)
        model.fc = nn.Linear(model.fc.in_features, num_classes)
    elif arch == "efficientnet_b0":
        model = _safe_construct(torchvision.models.efficientnet_b0, torchvision.models.EfficientNet_B0_Weights.IMAGENET1K_V1)
        in_features = model.classifier[-1].in_features
        model.classifier[-1] = nn.Linear(in_features, num_classes)
    elif arch == "mobilenet_v3_small":
        model = _safe_construct(torchvision.models.mobilenet_v3_small, torchvision.models.MobileNet_V3_Small_Weights.IMAGENET1K_V1)
        in_features = model.classifier[-1].in_features
        model.classifier[-1] = nn.Linear(in_features, num_classes)
    else:
        raise KeyError(f"Unsupported torchvision architecture: {architecture}")

    try_wrap_classifier_with_dropout(model, dropout)
    return model

"""## Section K, L, M — Testing and Evaluating Our Models

How do we know if a model is actually good? We track a bunch of metrics:
- **Accuracy**: How many did it get right?
- **Macro F1**: A balanced score that makes sure we are doing well on *both* males and females, even if one is more common.
- **Confusion Matrices**: A visual grid showing what the model got confused by.
- **Calibration**: If the model says it's 90% sure, is it actually right 90% of the time?

We also create **Challenge Suites**—we take the test images and purposefully make them dark, blurry, or noisy to see if the model falls apart.
"""

# SECTION K + L + M — Metrics, calibration, threshold sweeps, challenge suites, and evaluation

def expected_calibration_error(y_true: np.ndarray, probs: np.ndarray, n_bins: int = 15) -> float:
    confidences = probs.max(axis=1)
    predictions = probs.argmax(axis=1)
    correctness = (predictions == y_true).astype(float)
    bins = np.linspace(0.0, 1.0, n_bins + 1)
    ece = 0.0
    for i in range(n_bins):
        lo, hi = bins[i], bins[i + 1]
        mask = (confidences >= lo) & (confidences < hi if i < n_bins - 1 else confidences <= hi)
        if mask.sum() == 0:
            continue
        bin_acc = correctness[mask].mean()
        bin_conf = confidences[mask].mean()
        ece += (mask.mean()) * abs(bin_acc - bin_conf)
    return float(ece)

def safe_binary_metrics(y_true: np.ndarray, probs_pos: np.ndarray) -> Dict[str, float]:
    out = {"roc_auc": float("nan"), "pr_auc": float("nan"), "brier_score": float("nan"), "log_loss": float("nan")}
    try:
        if len(np.unique(y_true)) == 2:
            out["roc_auc"] = float(roc_auc_score(y_true, probs_pos))
            out["pr_auc"] = float(average_precision_score(y_true, probs_pos))
            out["brier_score"] = float(np.mean((probs_pos - y_true) ** 2))
            out["log_loss"] = float(log_loss(y_true, np.clip(probs_pos, 1e-6, 1 - 1e-6)))
    except Exception:
        pass
    return out

def compute_prediction_metrics(pred_df: pd.DataFrame) -> Dict[str, Any]:
    y_true = pred_df["label_true_idx"].to_numpy()
    y_pred = pred_df["pred_idx"].to_numpy()
    probs = pred_df[[f"prob_{name}" for name in CFG.class_names]].to_numpy()
    precision, recall, f1_vals, support = precision_recall_fscore_support(
        y_true,
        y_pred,
        labels=list(range(CFG.expected_num_classes)),
        zero_division=0,
    )
    per_class = {
        CFG.class_names[i]: {
            "precision": float(precision[i]),
            "recall": float(recall[i]),
            "f1": float(f1_vals[i]),
            "support": int(support[i]),
        }
        for i in range(CFG.expected_num_classes)
    }
    extra_binary = safe_binary_metrics(y_true, probs[:, 1]) if CFG.expected_num_classes == 2 else {}
    metrics = {
        "accuracy": float(accuracy_score(y_true, y_pred)),
        "balanced_accuracy": float(balanced_accuracy_score(y_true, y_pred)) if len(np.unique(y_true)) > 1 else float("nan"),
        "macro_f1": float(f1_score(y_true, y_pred, average="macro", zero_division=0)),
        "worst_class_recall": float(np.min(recall)) if len(recall) else float("nan"),
        "ece": expected_calibration_error(y_true, probs, n_bins=CFG.ece_bins),
        "confusion_matrix_raw": confusion_matrix(y_true, y_pred, labels=list(range(CFG.expected_num_classes))).tolist(),
        "confusion_matrix_normalized": confusion_matrix(y_true, y_pred, labels=list(range(CFG.expected_num_classes)), normalize="true").tolist(),
        "classification_report": classification_report(
            y_true,
            y_pred,
            labels=list(range(CFG.expected_num_classes)),
            target_names=CFG.class_names,
            output_dict=True,
            zero_division=0,
        ),
        "per_class": per_class,
    }
    metrics.update(extra_binary)
    return metrics

def compute_threshold_sweep(pred_df: pd.DataFrame, thresholds: Sequence[float]) -> pd.DataFrame:
    y_true = pred_df["label_true_idx"].to_numpy()
    y_pred = pred_df["pred_idx"].to_numpy()
    confidence = pred_df["confidence"].to_numpy()
    probs = pred_df[[f"prob_{name}" for name in CFG.class_names]].to_numpy()

    rows = []
    for thr in thresholds:
        keep = confidence >= thr
        abstain_count = int((~keep).sum())
        coverage = float(keep.mean()) if len(keep) else 0.0
        overall_acc = float((((y_pred == y_true) & keep).sum()) / max(1, len(y_true)))

        if keep.sum() > 0:
            yt = y_true[keep]
            yp = y_pred[keep]
            conf_probs = probs[keep]
            macro_f1 = float(f1_score(yt, yp, average="macro", zero_division=0))
            bal_acc = float(balanced_accuracy_score(yt, yp)) if len(np.unique(yt)) > 1 else float("nan")
            worst_recall = float(np.min(precision_recall_fscore_support(yt, yp, labels=list(range(CFG.expected_num_classes)), zero_division=0)[1]))
            confident_acc = float(accuracy_score(yt, yp))
            confident_ece = expected_calibration_error(yt, conf_probs, n_bins=CFG.ece_bins)
        else:
            macro_f1 = float("nan")
            bal_acc = float("nan")
            worst_recall = float("nan")
            confident_acc = float("nan")
            confident_ece = float("nan")

        rows.append({
            "threshold": float(thr),
            "coverage": coverage,
            "abstained_images": abstain_count,
            "overall_accuracy_including_abstentions_as_wrong": overall_acc,
            "confident_accuracy": confident_acc,
            "confident_macro_f1": macro_f1,
            "confident_balanced_accuracy": bal_acc,
            "confident_worst_class_recall": worst_recall,
            "confident_ece": confident_ece,
        })
    return pd.DataFrame(rows)

def choose_recommended_threshold(sweep_df: pd.DataFrame, min_coverage: float = 0.80) -> Dict[str, Any]:
    work = sweep_df.copy()
    eligible = work[work["coverage"] >= min_coverage].copy()
    if eligible.empty:
        eligible = work.copy()
    best_macro = eligible.sort_values(
        by=["confident_macro_f1", "confident_balanced_accuracy", "coverage"],
        ascending=[False, False, False],
        na_position="last",
    ).iloc[0].to_dict()
    best_overall = work.sort_values(
        by=["overall_accuracy_including_abstentions_as_wrong", "coverage"],
        ascending=[False, False],
        na_position="last",
    ).iloc[0].to_dict()
    return {
        "best_threshold_by_macro_f1": best_macro,
        "best_threshold_by_overall_accuracy": best_overall,
    }

