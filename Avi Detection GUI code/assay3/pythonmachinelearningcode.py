def run_training_experiment(spec: ExperimentSpec) -> Dict[str, Any]:
    run_dir = get_run_dir(spec)
    run_dir.mkdir(parents=True, exist_ok=True)
    save_json(run_dir / "spec.json", asdict(spec))
    status_path = run_dir / "status.json"

    if status_path.exists():
        status = load_json(status_path)
        if status.get("status") == "success" and (run_dir / "metrics_summary.json").exists():
            print(f"Skipping completed run: {spec.run_name}")
            return status

    try:
        seed_everything(spec.seed, deterministic=CFG.deterministic)
        model = build_model_from_spec(spec).to(CFG.device)
        train_loader, valid_loader, test_loader, class_weight_tensor, weighted_sampler = build_dataloaders_for_spec(spec)

        loss_fn = build_loss_function(
            spec,
            class_weight_tensor.to(CFG.device) if class_weight_tensor is not None and spec.class_balancing in {"auto", "class_weight"} else None,
        )

        if spec.freeze_backbone_epochs > 0:
            freeze_backbone(model, spec)
        else:
            unfreeze_all(model)

        optimizer = build_optimizer(model, spec)
        scheduler = build_scheduler(optimizer, total_epochs=spec.epochs)
        scaler = torch.cuda.amp.GradScaler(enabled=(CFG.use_amp and CFG.device.startswith("cuda")))

        history_rows: List[Dict[str, Any]] = []
        best_metric = -float("inf")
        best_epoch = -1
        epochs_without_improvement = 0

        for epoch in range(1, spec.epochs + 1):
            if epoch == spec.freeze_backbone_epochs + 1 and spec.freeze_backbone_epochs > 0:
                unfreeze_all(model)
                optimizer = build_optimizer(model, spec)
                scheduler = build_scheduler(optimizer, total_epochs=max(1, spec.epochs - epoch + 1))

            train_stats = train_one_epoch(
                model,
                train_loader,
                optimizer,
                loss_fn,
                device=CFG.device,
                scaler=scaler,
                max_grad_norm=CFG.max_grad_norm,
            )
            valid_pred_df = predict_with_model(model, valid_loader, device=CFG.device)
            valid_metric = float(f1_score(valid_pred_df["label_true_idx"], valid_pred_df["pred_idx"], average="macro", zero_division=0))

            hist_row = {
                "epoch": epoch,
                **train_stats,
                "valid_macro_f1": valid_metric,
                "valid_accuracy": float(accuracy_score(valid_pred_df["label_true_idx"], valid_pred_df["pred_idx"])),
            }
            history_rows.append(hist_row)

            if valid_metric > best_metric:
                best_metric = valid_metric
                best_epoch = epoch
                epochs_without_improvement = 0
                save_model_bundle(bundle_checkpoint_path(run_dir, "best"), model, spec, extra={"best_epoch": epoch})
            else:
                epochs_without_improvement += 1

            save_model_bundle(bundle_checkpoint_path(run_dir, "last"), model, spec, extra={"epoch": epoch})
            scheduler.step()

            print(f"Epoch {epoch:03d} | train_loss={train_stats['train_loss']:.4f} | train_acc={train_stats['train_accuracy']:.3f} | valid_macro_f1={valid_metric:.3f}")

            if epochs_without_improvement >= spec.patience:
                print(f"Early stopping at epoch {epoch} with best_epoch={best_epoch} and best_valid_macro_f1={best_metric:.4f}")
                break

        save_training_history(history_rows, run_dir)

        status = {
            "status": "trained",
            "run_name": spec.run_name,
            "best_epoch": best_epoch,
            "best_metric": best_metric,
            "bundle_best": str(bundle_checkpoint_path(run_dir, "best").resolve()),
            "bundle_last": str(bundle_checkpoint_path(run_dir, "last").resolve()),
            "history_csv": str((run_dir / "history.csv").resolve()),
        }
        save_json(status_path, status)
        return status

    except Exception as exc:
        err_text = traceback.format_exc()
        (run_dir / "error.txt").write_text(err_text, encoding="utf-8")
        status = {
            "status": "failed",
            "run_name": spec.run_name,
            "error": str(exc),
        }
        save_json(status_path, status)
        print_rule(f"RUN FAILED — {spec.run_name}")
        print(err_text)
        return status

# PATCH — Preserve old-checkpoint classifier weights when class count already matches

def _find_last_linear(module: nn.Module) -> Optional[nn.Linear]:
    for submodule in reversed(list(module.modules())):
        if isinstance(submodule, nn.Linear):
            return submodule
    return None

def build_ultralytics_model(architecture_or_ckpt: str, num_classes: int, dropout: float) -> nn.Module:
    yolo = YOLO(architecture_or_ckpt)
    model = yolo.model
    last_linear = _find_last_linear(model)
    if last_linear is None:
        raise RuntimeError(f"Could not locate a final Linear layer for Ultralytics model: {architecture_or_ckpt}")
    if int(last_linear.out_features) != int(num_classes):
        ok = replace_last_linear_in_module(model, num_classes)
        if not ok:
            raise RuntimeError(f"Could not replace the classifier head for Ultralytics model: {architecture_or_ckpt}")
    try_wrap_classifier_with_dropout(model, dropout)
    if hasattr(model, "names"):
        model.names = {i: name for i, name in enumerate(CFG.class_names)}
    return model

def build_model_from_spec(spec: ExperimentSpec) -> nn.Module:
    if spec.family == "old_checkpoint":
        if CFG.old_model_path is None or not Path(CFG.old_model_path).exists():
            raise FileNotFoundError("Old checkpoint path is not available.")
        return build_ultralytics_model(str(CFG.old_model_path), num_classes=CFG.expected_num_classes, dropout=spec.dropout)
    if spec.family == "generic_pretrained":
        return build_torchvision_model(spec.architecture, num_classes=CFG.expected_num_classes, pretrained=True, dropout=spec.dropout)
    if spec.family == "generic_pretrained_2":
        return build_torchvision_model(spec.architecture, num_classes=CFG.expected_num_classes, pretrained=True, dropout=spec.dropout)
    if spec.family == "scratch_yolo":
        return build_ultralytics_model(spec.architecture, num_classes=CFG.expected_num_classes, dropout=spec.dropout)
    if spec.family == "scratch_torchvision":
        return build_torchvision_model(spec.architecture, num_classes=CFG.expected_num_classes, pretrained=False, dropout=spec.dropout)
    raise KeyError(f"Unknown spec.family: {spec.family}")

