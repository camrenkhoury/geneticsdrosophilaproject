def choose_deployment_candidate(best_sets: Dict[str, Dict[str, Any]]) -> Dict[str, Any]:
    clean = best_sets["best_clean_validation"]
    robust = best_sets["best_robust_validation"]

    clean_drop = float(clean.get("valid_macro_f1", np.nan)) - float(clean.get("valid_challenge_mean_macro_f1", clean.get("valid_macro_f1", np.nan)))
    robust_drop = float(robust.get("valid_macro_f1", np.nan)) - float(robust.get("valid_challenge_mean_macro_f1", robust.get("valid_macro_f1", np.nan)))

    if (
        float(robust.get("valid_challenge_mean_macro_f1", -1.0)) >= float(clean.get("valid_challenge_mean_macro_f1", -1.0)) - 0.01
        and robust_drop <= clean_drop + 0.02
    ):
        selected = robust.copy()
        selected["selection_rationale"] = "robust_candidate_preferred"
    else:
        selected = clean.copy()
        selected["selection_rationale"] = "clean_candidate_preferred"
    return selected

