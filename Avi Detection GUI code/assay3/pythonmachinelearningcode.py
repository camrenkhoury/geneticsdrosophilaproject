def replace_last_linear_in_module(module: nn.Module, out_features: int) -> bool:
    named = list(module.named_modules())
    for name, submodule in reversed(named):
        if isinstance(submodule, nn.Linear):
            parent = module
            parent_name = name.rsplit(".", 1)[0] if "." in name else ""
            if parent_name:
                for token in parent_name.split("."):
                    parent = getattr(parent, token)
            last_name = name.split(".")[-1]
            new_layer = nn.Linear(submodule.in_features, out_features)
            setattr(parent, last_name, new_layer)
            return True
    return False

def try_wrap_classifier_with_dropout(module: nn.Module, p: float) -> None:
    if p <= 0:
        return
    if hasattr(module, "fc") and isinstance(module.fc, nn.Linear):
        module.fc = nn.Sequential(nn.Dropout(p), module.fc)
        return
    if hasattr(module, "classifier"):
        classifier = getattr(module, "classifier")
        if isinstance(classifier, nn.Linear):
            setattr(module, "classifier", nn.Sequential(nn.Dropout(p), classifier))
            return
        if isinstance(classifier, nn.Sequential):
            layers = list(classifier.children())
            if layers and isinstance(layers[-1], nn.Linear):
                layers.insert(len(layers) - 1, nn.Dropout(p))
                setattr(module, "classifier", nn.Sequential(*layers))
                return
    # Generic fallback: wrap the final linear inside its parent.
    named = list(module.named_modules())
    for name, submodule in reversed(named):
        if isinstance(submodule, nn.Linear):
            parent = module
            parent_name = name.rsplit(".", 1)[0] if "." in name else ""
            if parent_name:
                for token in parent_name.split("."):
                    parent = getattr(parent, token)
            last_name = name.split(".")[-1]
            setattr(parent, last_name, nn.Sequential(nn.Dropout(p), submodule))
            return

