def find_last_conv_layer(model: nn.Module) -> Optional[nn.Module]:
    for module in reversed(list(model.modules())):
        if isinstance(module, nn.Conv2d):
            return module
    return None

class GradCAMRunner:
    def __init__(self, model: nn.Module, target_layer: nn.Module):
        self.model = model
        self.target_layer = target_layer
        self.activations = None
        self.gradients = None
        self.fwd_handle = target_layer.register_forward_hook(self._forward_hook)
        self.bwd_handle = target_layer.register_full_backward_hook(self._backward_hook)

    def _forward_hook(self, module, input, output):
        self.activations = output.detach()

    def _backward_hook(self, module, grad_input, grad_output):
        self.gradients = grad_output[0].detach()

    def close(self):
        self.fwd_handle.remove()
        self.bwd_handle.remove()

    def generate(self, x: torch.Tensor, class_idx: int) -> np.ndarray:
        self.model.zero_grad(set_to_none=True)
        logits = extract_logits(self.model(x))
        score = logits[:, class_idx].sum()
        score.backward(retain_graph=False)

        acts = self.activations
        grads = self.gradients
        if acts is None or grads is None:
            raise RuntimeError("Grad-CAM hooks did not capture activations/gradients.")

        weights = grads.mean(dim=(2, 3), keepdim=True)
        cam = (weights * acts).sum(dim=1, keepdim=True)
        cam = torch.relu(cam)
        cam = F.interpolate(cam, size=x.shape[-2:], mode="bilinear", align_corners=False)
        cam = cam[0, 0].detach().cpu().numpy()
        cam = (cam - cam.min()) / (cam.max() - cam.min() + 1e-8)
        return cam

def overlay_cam_on_image(img: Image.Image, cam: np.ndarray, alpha: float = 0.35) -> Image.Image:
    img_arr = np.asarray(img.convert("RGB")).astype(np.float32)
    heatmap = plt.get_cmap("jet")(cam)[..., :3]
    heatmap = (heatmap * 255.0).astype(np.uint8)
    overlay = (1 - alpha) * img_arr + alpha * heatmap.astype(np.float32)
    return Image.fromarray(np.clip(overlay, 0, 255).astype(np.uint8))

def generate_gradcam_examples(record: Dict[str, Any], split_name: str = "valid", max_items: int = 10) -> None:
    if not CFG.run_gradcam or record.get("run_name") == "z_soft_vote_ensemble":
        return
    if record.get("run_name") == "a_old_checkpoint_eval_only":
        # Build a temporary bundle-like model directly from the checkpoint.
        spec = make_spec(
            run_name="__baseline_cam__",
            family="old_checkpoint",
            architecture="old_checkpoint",
            init_mode="eval_only",
            branch_name="RAW",
            aug_policy="none",
            image_size=CFG.image_size,
            batch_size=CFG.batch_size,
            epochs=1,
            patience=1,
            lr=CFG.lr,
            weight_decay=CFG.weight_decay,
        )
        model = build_model_from_spec(spec).to(CFG.device)
        run_dir = CFG.paths.analysis_root / "gradcam" / record["run_name"]
        pred_path = CFG.paths.baseline_root / f"{split_name}_pristine" / "predictions.csv"
    else:
        spec = record_to_spec(record)
        model, _, _ = load_model_bundle(Path(record["bundle_best"]))
        model = model.to(CFG.device)
        run_dir = CFG.paths.analysis_root / "gradcam" / record["run_name"]
        pred_path = get_run_dir(spec) / "eval" / f"{split_name}_pristine" / "predictions.csv"

    if not pred_path.exists():
        return

    run_dir.mkdir(parents=True, exist_ok=True)
    pred_df = pd.read_csv(pred_path)
    candidates = pd.concat([
        pred_df[pred_df["is_correct"] == True].sort_values("confidence", ascending=False).head(max_items // 2),
        pred_df[pred_df["is_correct"] == False].sort_values("confidence", ascending=False).head(max_items // 2),
    ], ignore_index=True)
    if candidates.empty:
        return

    target_layer = find_last_conv_layer(model)
    if target_layer is None:
        print(f"Skipping Grad-CAM for {record['run_name']} — no Conv2d layer found.")
        return

    cam_runner = GradCAMRunner(model, target_layer)
    transform = build_eval_transform(int(record.get("image_size", CFG.image_size)))

    for i, row in enumerate(candidates.itertuples(index=False)):
        img = Image.open(row.filepath).convert("RGB")
        x = transform(img).unsqueeze(0).to(CFG.device)
        class_idx = int(row.pred_idx)
        cam = cam_runner.generate(x, class_idx)
        overlay = overlay_cam_on_image(img.resize((x.shape[-1], x.shape[-2])), cam)
        overlay.save(run_dir / f"{i:02d}__true_{row.label_true}__pred_{row.pred_label}__conf_{row.confidence:.3f}.png")
    cam_runner.close()
    del model
    if torch.cuda.is_available():
        torch.cuda.empty_cache()

def extract_embeddings_for_record(record: Dict[str, Any], split_name: str = "valid") -> Optional[pd.DataFrame]:
    if not CFG.run_embedding_analysis or record.get("run_name") == "z_soft_vote_ensemble":
        return None

    if record.get("run_name") == "a_old_checkpoint_eval_only":
        spec = make_spec(
            run_name="__baseline_embed__",
            family="old_checkpoint",
            architecture="old_checkpoint",
            init_mode="eval_only",
            branch_name="RAW",
            aug_policy="none",
            image_size=CFG.image_size,
            batch_size=CFG.batch_size,
            epochs=1,
            patience=1,
            lr=CFG.lr,
            weight_decay=CFG.weight_decay,
        )
        model = build_model_from_spec(spec)
        manifest_df = BRANCH_MANIFESTS["RAW"].copy() if split_name == "all_splits" else BRANCH_MANIFESTS["RAW"][BRANCH_MANIFESTS["RAW"]["split_canonical"] == split_name].copy()
    else:
        spec = record_to_spec(record)
        model, _, _ = load_model_bundle(Path(record["bundle_best"]))
        manifest_df = BRANCH_MANIFESTS[spec.branch_name].copy() if split_name == "all_splits" else BRANCH_MANIFESTS[spec.branch_name][BRANCH_MANIFESTS[spec.branch_name]["split_canonical"] == split_name].copy()

    model = model.to(CFG.device)
    holder: Dict[str, torch.Tensor] = {}
    target_linear = None
    for module in reversed(list(model.modules())):
        if isinstance(module, nn.Linear):
            target_linear = module
            break
    hook = None
    if target_linear is not None:
        def _pre_hook(module, args):
            holder["feat"] = args[0].detach()
        hook = target_linear.register_forward_pre_hook(_pre_hook)

    ds = ManifestImageDataset(manifest_df, image_path_col="branch_filepath", transform=build_eval_transform(int(record.get("image_size", CFG.image_size))))
    loader = torch.utils.data.DataLoader(ds, batch_size=CFG.eval_batch_size, shuffle=False, num_workers=CFG.num_workers)

    rows = []
    with torch.inference_mode():
        for batch_x, batch_y, batch_meta in tqdm(loader, desc=f"embed {record['run_name']}", leave=False):
            batch_x = batch_x.to(CFG.device)
            logits = extract_logits(model(batch_x))
            feats = holder.get("feat", logits).detach().cpu().numpy()
            if feats.ndim > 2:
                feats = feats.reshape(feats.shape[0], -1)
            for i in range(len(batch_y)):
                rec = {
                    "file_sha1": batch_meta["file_sha1"][i] if isinstance(batch_meta["file_sha1"], list) else batch_meta["file_sha1"],
                    "label_true_idx": int(batch_y[i].item()),
                    "label_true": CFG.class_names[int(batch_y[i].item())],
                    "filepath": batch_meta["filepath"][i] if isinstance(batch_meta["filepath"], list) else batch_meta["filepath"],
                    "split_canonical": batch_meta["split_canonical"][i] if isinstance(batch_meta["split_canonical"], list) else batch_meta["split_canonical"],
                }
                for j in range(feats.shape[1]):
                    rec[f"feat_{j}"] = float(feats[i, j])
                rows.append(rec)
    if hook is not None:
        hook.remove()
    del model
    if torch.cuda.is_available():
        torch.cuda.empty_cache()
    return pd.DataFrame(rows)

def reduce_and_plot_embeddings(embed_df: pd.DataFrame, out_dir: Path, title_prefix: str) -> None:
    if embed_df is None or embed_df.empty:
        return
    out_dir.mkdir(parents=True, exist_ok=True)
    feat_cols = [c for c in embed_df.columns if c.startswith("feat_")]
    if not feat_cols:
        return
    X = embed_df[feat_cols].to_numpy(dtype=np.float32)
    X = PCA(n_components=min(25, X.shape[1], max(2, X.shape[0] - 1))).fit_transform(X)

    reducers = {"pca2": PCA(n_components=2, random_state=CFG.random_seed)}
    if HAS_UMAP:
        reducers["umap2"] = umap.UMAP(n_components=2, random_state=CFG.random_seed, n_neighbors=min(15, len(embed_df) - 1))
    else:
        reducers["tsne2"] = TSNE(n_components=2, random_state=CFG.random_seed, init="pca", learning_rate="auto")

    for name, reducer in reducers.items():
        try:
            Z = reducer.fit_transform(X)
        except Exception as exc:
            print(f"Embedding reducer failed ({name}): {exc}")
            continue
        plot_df = embed_df.copy()
        plot_df["x"] = Z[:, 0]
        plot_df["y"] = Z[:, 1]

        for color_col in ["label_true"]:
            plt.figure(figsize=(6, 5), dpi=140)
            sns.scatterplot(data=plot_df, x="x", y="y", hue=color_col, s=40, alpha=0.85)
            plt.title(f"{title_prefix} — {name} colored by {color_col}")
            plt.tight_layout()
            plt.savefig(out_dir / f"{name}_{color_col}.png")
            plt.close()

def nearest_neighbor_leakage_audit(embed_df: pd.DataFrame, split_name: str, out_path: Path) -> None:
    if embed_df is None or embed_df.empty or not CFG.run_nearest_neighbor_audit:
        return
    feat_cols = [c for c in embed_df.columns if c.startswith("feat_")]
    if len(feat_cols) < 2:
        return
    X = embed_df[feat_cols].to_numpy(dtype=np.float32)
    n_neighbors = min(6, len(embed_df))
    nn_model = NearestNeighbors(n_neighbors=n_neighbors, metric="cosine")
    nn_model.fit(X)
    distances, indices = nn_model.kneighbors(X)

    rows = []
    for i in range(len(embed_df)):
        for rank in range(1, n_neighbors):
            j = int(indices[i, rank])
            sim = 1.0 - float(distances[i, rank])
            rows.append({
                "query_file_sha1": embed_df.iloc[i]["file_sha1"],
                "neighbor_file_sha1": embed_df.iloc[j]["file_sha1"],
                "query_filepath": embed_df.iloc[i]["filepath"],
                "neighbor_filepath": embed_df.iloc[j]["filepath"],
                "query_label": embed_df.iloc[i]["label_true"],
                "neighbor_label": embed_df.iloc[j]["label_true"],
                "query_split": embed_df.iloc[i].get("split_canonical", split_name),
                "neighbor_split": embed_df.iloc[j].get("split_canonical", split_name),
                "cross_split": embed_df.iloc[i].get("split_canonical", split_name) != embed_df.iloc[j].get("split_canonical", split_name),
                "cosine_similarity": sim,
                "split_name": split_name,
            })
    df_rows = pd.DataFrame(rows)
    if not df_rows.empty:
        df_rows = df_rows.sort_values(["cross_split", "cosine_similarity"], ascending=[False, False])
    df_rows.to_csv(out_path, index=False)

