def resolve_old_model_path(cfg: NotebookConfig) -> Optional[Path]:
    candidates: List[Path] = []
    if cfg.old_model_path is not None:
        candidates.append(Path(cfg.old_model_path))
    for raw in cfg.old_model_search_order:
        candidates.append(Path(raw))
    search_roots = [Path("."), Path("/content"), Path("/mnt/data")]
    for root in search_roots:
        if root.exists():
            candidates.extend(sorted(root.glob("*.pt")))
    seen = set()
    deduped = []
    for path in candidates:
        path = Path(path)
        if str(path) not in seen:
            seen.add(str(path))
            deduped.append(path)
    for path in deduped:
        if path.exists():
            return path.resolve()
    return None

