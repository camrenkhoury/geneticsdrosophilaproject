def load_model_bundle(path: Path) -> Tuple[nn.Module, ExperimentSpec, Dict[str, Any]]:
    bundle = torch.load(path, map_location="cpu")
    if not isinstance(bundle, dict) or "state_dict" not in bundle or "spec" not in bundle:
        raise ValueError(f"File does not look like a custom notebook bundle: {path}")
    spec = ExperimentSpec(**bundle["spec"])
    model = build_model_from_spec(spec)
    model.load_state_dict(bundle["state_dict"], strict=True)
    model.eval()
    return model, spec, bundle.get("extra", {})

def prepare_manifests_for_spec(spec: ExperimentSpec, combine_train_valid: bool = False) -> Tuple[pd.DataFrame, pd.DataFrame, pd.DataFrame]:
    if spec.branch_name not in BRANCH_MANIFESTS:
        raise KeyError(f"Branch not materialized: {spec.branch_name}")
    branch_df = BRANCH_MANIFESTS[spec.branch_name].copy()

    if spec.use_offline_aug_cache and not spec.use_online_aug:
        train_aug_df = materialize_offline_aug_manifest(
            spec.branch_name,
            spec.aug_policy,
            force=CFG.force_regenerate_aug_cache,
        )
        train_df = train_aug_df[train_aug_df["split_canonical"] == "train"].copy()
        if combine_train_valid:
            valid_aug_df = BRANCH_MANIFESTS[spec.branch_name].copy()
            valid_aug_df = valid_aug_df[valid_aug_df["split_canonical"] == "valid"].copy()
            valid_aug_df["aug_policy"] = spec.aug_policy
            valid_aug_df["is_augmented"] = False
            valid_aug_df["aug_copy_idx"] = -1
            valid_aug_df["augmented_filepath"] = valid_aug_df["branch_filepath"]
            train_df = pd.concat([train_df, valid_aug_df], ignore_index=True)
    else:
        train_df = branch_df[branch_df["split_canonical"] == "train"].copy()
        if combine_train_valid:
            train_df = branch_df[branch_df["split_canonical"].isin(["train", "valid"])].copy()
        train_df["augmented_filepath"] = train_df["branch_filepath"]

    valid_df = branch_df[branch_df["split_canonical"] == "valid"].copy()
    test_df = branch_df[branch_df["split_canonical"] == "test"].copy()
    return train_df.reset_index(drop=True), valid_df.reset_index(drop=True), test_df.reset_index(drop=True)

